// Writes NARRATION.md, the timed script for the narrator, from the lines the video uses right now.
// node lib/narration-md.mjs   (build.sh runs it after audio/guide-vo.mjs, so the times are always current)
import fs from "node:fs";
import path from "node:path";
import { root, project, duration, readJson } from "./project.mjs";

const script = readJson("stage/script.json", []);
const cues = readJson("stage/cues.json", []);
const durations = readJson("stage/data/vo-durations.json", {});
const facts = readJson("stage/data/facts.json", {});
const clock = (seconds) => `${Math.floor(seconds / 60)}:${(seconds % 60).toFixed(1).padStart(4, "0")}`;
const plain = (text) => text.replace(/\*/g, "").replace(/\s*\|\s*/g, " ");
const scenes = [
  ["hook-1", "Hook"],
  ["method-1", "Method"],
  ["agents-1", "Agents"],
  ["report-1", "Report page"],
  ["bench-1", "Benchmark"],
  ["signal-1", "Evidence and signals"],
  ["watch-1", "Watch agent"],
  ["new", "Close"],
];
const sceneOf = Object.fromEntries(scenes);
const words = cues.reduce((sum, cue) => sum + plain(cue.text).split(/\s+/).length, 0);
const BEATS = { mapping: "step 5 mapping", asiOne: "ASI:One chat", benchmark: "benchmark scores", candidate: "a candidate new signal", creao: "Creao scheduled run" };
const pendingBeats = Object.keys(BEATS).filter((name) => !facts.status?.[name]).map((name) => BEATS[name]);

const rows = cues.map((cue) => {
  const end = cue.at + (durations[cue.id] ?? 0);
  const scene = sceneOf[cue.id] ? `**${sceneOf[cue.id]}** ` : "";
  return `| ${clock(cue.at)} | ${clock(end)} | ${scene}\`${cue.id}\` | ${plain(cue.text)} |`;
});
const variants = script
  .filter((line) => line.ready)
  .flatMap((line) =>
    [line.ready].flat().map((variant) => {
      const active = cues.find((cue) => cue.id === line.id)?.variant === `ready:${variant.when}`;
      const wording = variant.stop ? `_The build stops and asks for a rewrite: ${variant.stop}._` : plain(variant.text);
      return `| \`${line.id}\` | ${variant.when} | ${active ? "in use" : "waiting"} | ${wording} |`;
    }),
  );

const document = `# Narration: timed script

Generated by \`lib/narration-md.mjs\` from \`stage/script.json\` and the captured facts on ${new Date().toISOString().slice(0, 10)}. Do not edit
by hand: change \`stage/script.json\`, then run \`./build.sh\`.

The video is ${duration.toFixed(1)} s. ${cues.length} lines, ${words} words. Times are where the guide voice (macOS \`say\`)
starts and ends each line; a person reading a little faster or slower is fine, because the recording booth
re-times the captions to the real take. Leave the pauses: the picture needs them.

${pendingBeats.length ? `Beats still pending, read with their pending wording: ${pendingBeats.join(", ")}.` : "Every beat is real; all lines use their final wording."}

## How to read it

- Read at a calm pace, a little slower than conversation. Smile on the first line.
- Say the numbers the way they are written: "eighty-six of fifty-four thousand and forty-six".
- Say "fixture" clearly in \`report-2\`. The rule for this video is that the fixture is named aloud whenever it is on screen.
- Stress the last word of the closing line: "already ran the *trial*."

## Script

| Starts | Ends | Line | Narration |
| --- | --- | --- | --- |
${rows.join("\n")}

## Wording that changes when a beat becomes real

\`./build.sh\` swaps these in by itself once \`capture/facts.mjs\` sees the beat is real (or \`stage/status.json\` forces it).
Re-record those lines as pickups in the booth after the swap.

| Line | Beat | Now | Final wording |
| --- | --- | --- | --- |
${variants.join("\n")}
`;
fs.writeFileSync(path.join(root, "NARRATION.md"), document);
console.log(`wrote NARRATION.md (${cues.length} lines, ${words} words, ${project.name})`);
